const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("codeHarborX", {
  packagingStatus: () => ipcRenderer.invoke('packaging:status'),
  selectPackagingFolder: () => ipcRenderer.invoke('packaging:select'),
  buildPackage: input => ipcRenderer.invoke('packaging:build', input),
  revealPackage: index => ipcRenderer.invoke('packaging:reveal', index),
  onPackagingStatus: callback => ipcRenderer.on('packaging:status', (_event, status) => callback(status)),
  deleteRecord: (collection, id) => ipcRenderer.invoke('platform:delete-record', collection, id),
  builderDeleteProject: id => ipcRenderer.invoke('builder:delete-project', id),
  builderDeleteFile: (id, rel) => ipcRenderer.invoke('builder:delete-file', id, rel),
  configureTunnel: input => ipcRenderer.invoke('tunnel:configure', input),
  forgetTunnelCredential: () => ipcRenderer.invoke('tunnel:forget'),
  startTunnel: () => ipcRenderer.invoke('tunnel:start'),
  stopTunnel: () => ipcRenderer.invoke('tunnel:stop'),
  restartTunnel: () => ipcRenderer.invoke('tunnel:restart'),
  selectTunnelExecutable: () => ipcRenderer.invoke('tunnel:select'),
  onTunnelStatus: callback => ipcRenderer.on('tunnel:status', (_event, status) => callback(status)),
  getConfig: () => ipcRenderer.invoke("config:get"),
  saveConfig: (config) => ipcRenderer.invoke("config:save", config),
  getSnapshot: () => ipcRenderer.invoke("platform:snapshot"),
  addProject: (input) => ipcRenderer.invoke("platform:add-project", input),
  recordBackup: (input) => ipcRenderer.invoke("platform:record-backup", input),
  addActivity: (message) => ipcRenderer.invoke("platform:add-activity", message),
  testNas: (nasRoot) => ipcRenderer.invoke("nas:test", nasRoot),
  scanBackups: (nasRoot) => ipcRenderer.invoke("nas:scan", nasRoot),
  openNas: (nasRoot) => ipcRenderer.invoke("nas:open", nasRoot),
  checkOllama: () => ipcRenderer.invoke("ollama:check"),
  builderStatus: () => ipcRenderer.invoke("builder:status"),
  builderCreate: (input) => ipcRenderer.invoke("builder:create", input),
  builderListFiles: (projectId) => ipcRenderer.invoke("builder:list-files", projectId),
  builderReadFile: (projectId, filePath) => ipcRenderer.invoke("builder:read-file", projectId, filePath),
  builderWriteFile: (projectId, filePath, content) => ipcRenderer.invoke("builder:write-file", projectId, filePath, content),
  builderGenerate: (input) => ipcRenderer.invoke("builder:generate", input),
  builderStartPreview: (projectId) => ipcRenderer.invoke("builder:start-preview", projectId),
  builderStopPreview: (projectId) => ipcRenderer.invoke("builder:stop-preview", projectId),
  builderOpenFolder: (projectId) => ipcRenderer.invoke("builder:open-folder", projectId),
  openLocalControls: () => ipcRenderer.invoke("window:open-local-controls"),
  openDataFolder: () => ipcRenderer.invoke("system:open-data-folder"),
  systemInfo: () => ipcRenderer.invoke("system:info"),
  checkForUpdates: () => ipcRenderer.invoke("update:check"),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  onUpdateStatus: (callback) => ipcRenderer.on("update:status", (_event, status) => callback(status)),
  onPlatformStatus: (callback) => ipcRenderer.on("platform:status", (_event, status) => callback(status))
});
